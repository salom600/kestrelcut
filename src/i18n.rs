/// Translated + visually shaped string ready for egui.
pub fn tx(lang: Lang, k: K) -> String {
    let s = tr(lang, k);
    match lang {
        Lang::En => s.to_string(),
        Lang::Ar => arabic::shape_if_arabic(s),
    }
}
